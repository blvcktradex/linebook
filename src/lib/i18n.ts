export function fill(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? ""));
}

export function translateAction(label: string, t: Dict): string {
  const text = label.trim();
  const lower = text.toLowerCase();
  if (lower === "fold" || lower === "folds") return t.fold;
  if (lower === "check" || lower === "checks") return t.check;
  if (lower === "call" || lower === "calls") return t.call;
  if (/all-?in|jam/.test(lower)) return t.allIn;
  const over = text.match(/overbets?\s+(\d+%)/i);
  if (over) return `${t.overbet} ${over[1]}`;
  const bet = text.match(/bets?\s+(\d+%)/i);
  if (bet) return `${t.bet} ${bet[1]}`;
  const raise = text.match(/raises?\s*(.*)/i);
  if (raise) return raise[1] ? `${t.raise} ${raise[1]}` : t.raise;
  return text;
}

export function translateClass(primary: string, t: Dict): string {
  if (!primary) return "";
  const key = CLASS_KEY[primary];
  return key ? t[key] : primary.replace(/-/g, " ");
}

export function translateSubtitle(subtitle: string, t: Dict): string {
  return subtitle
    .replaceAll("Single raised", t.srp)
    .replaceAll("3-bet pot", t.threeBet)
    .replaceAll("two-tone", t.twoTone)
    .replaceAll("rainbow", t.rainbowWord)
    .replaceAll("paired", t.paired)
    .replace(/^River/, t.river);
}

